"""
UK Biobank fMRI Functional-Connectivity Pipeline
================================================

Builds 66x66 sparse FC matrices aligned, ROI-by-ROI and subject-by-subject,
to the 66-node sMRI tensor produced by Code/sMRI_proc.py, ready to feed
straight into a 66-node graph for GCN/GNN training.

Pipeline
--------
[Step 1/5] Read the 66-ROI ordering directly from the sMRI CSV header
           (so the fMRI pipeline can never drift out of sync with sMRI).
[Step 2/5] Build a name-based 68 -> 66 permutation by matching the sMRI
           ROIs against the fMRI 68-node atlas (DK_info_ukb.csv ordering:
           R-hemisphere first, then L). This drops the two temporalpole
           nodes (which UKB does not export in sMRI) and swaps the
           hemisphere blocks so the result is L-first to match sMRI.
[Step 3/5] Stream every subject in ukb_aparc_ts.mat, decode eid, compute
           the dense 68x68 Pearson FC, apply the permutation, then zero
           the diagonal. No per-subject threshold is applied here.
[Step 4/5] Restrict to subjects present in the sMRI CSV and reorder them
           to match the sMRI row order, so FC[i] and sMRI[i] share an eid.
[Step 5/5] Save:
             * corr_matrix.mat with FC_Matrices, Patient_IDs, ROI_Labels
               and the permutation/drop indices used.
             * roi_alignment.csv as a human-readable cross-check of
               (sMRI position, ROI name, fMRI source index).

Notes on the ROI mapping
------------------------
The teacher's reference (Reference material/ukb_individual_risk_score_v3.py)
maps `'TrT': 'temporalpole'`. That is incorrect for this dataset.
Authoritative source: /home/celery/uk_BIOBANK_DATA/imaging/atlas/DK_info_ukb.zip,
which contains DK_info_ukb.m. The parallel arrays ref_DKTROIs (34 names)
and ref_DKTROIs_Abb (33 abbrevs) make it explicit that UKB skips
`temporalpole`, so `TrT` is `transversetemporal`. Using the teacher's
mapping would have dropped the wrong nodes and silently misaligned every
edge in the GCN.
"""

import csv
import os

import h5py
import numpy as np
import scipy.io as sio


# --- CONFIGURATION ---
FMRI_PATH = '/home/celery/uk_BIOBANK_DATA/imaging/fMRI/BOLD/origin/ukb_aparc_ts.mat'
SMRI_CSV_PATH = '/home/celery/uk_BIOBANK_DATA/imaging/sMRI/UKB_Freesurfer_APARC.csv'
SAVE_FILE = '/home/celery/Project/TCG-Net/Data/corr_matrix.mat'
ROI_REPORT_FILE = '/home/celery/Project/TCG-Net/Data/roi_alignment.csv'


# 68-node fMRI atlas ordering used in ukb_aparc_ts.mat. Source of truth:
# /home/celery/uk_BIOBANK_DATA/imaging/atlas/DK_info_ukb.csv (rows 1-68),
# generated by DK_info_ukb.m. Cortex is laid out R-hemisphere first
# (ids 1-34), then L-hemisphere (ids 35-68); within each hemisphere ROIs
# are alphabetical except frontalpole/temporalpole/transversetemporal/
# insula are pushed to the end.
_FMRI_PER_HEMI = [
    'bankssts', 'caudalanteriorcingulate', 'caudalmiddlefrontal', 'cuneus',
    'entorhinal', 'fusiform', 'inferiorparietal', 'inferiortemporal',
    'isthmuscingulate', 'lateraloccipital', 'lateralorbitofrontal', 'lingual',
    'medialorbitofrontal', 'middletemporal', 'parahippocampal', 'paracentral',
    'parsopercularis', 'parsorbitalis', 'parstriangularis', 'pericalcarine',
    'postcentral', 'posteriorcingulate', 'precentral', 'precuneus',
    'rostralanteriorcingulate', 'rostralmiddlefrontal', 'superiorfrontal',
    'superiorparietal', 'superiortemporal', 'supramarginal', 'frontalpole',
    'temporalpole', 'transversetemporal', 'insula',
]
FMRI_68_LABELS = (
    [('R', n) for n in _FMRI_PER_HEMI] + [('L', n) for n in _FMRI_PER_HEMI]
)
_FMRI_INDEX = {pair: i for i, pair in enumerate(FMRI_68_LABELS)}
assert len(FMRI_68_LABELS) == 68

# UKB short codes (used in column names like SA_L_BST_2_0) -> DK region names.
# Authoritative source: parallel arrays ref_DKTROIs / ref_DKTROIs_Abb in
# DK_info_ukb.m. UKB exports 33 cortical ROIs per hemisphere (no temporalpole).
_UKB_ABBREV_TO_REGION = {
    'BST': 'bankssts', 'CACg': 'caudalanteriorcingulate',
    'CMF': 'caudalmiddlefrontal', 'Cu': 'cuneus', 'En': 'entorhinal',
    'Fp': 'frontalpole', 'Fu': 'fusiform', 'IP': 'inferiorparietal',
    'IT': 'inferiortemporal', 'Ins': 'insula', 'IstCg': 'isthmuscingulate',
    'LO': 'lateraloccipital', 'LOrF': 'lateralorbitofrontal', 'Lg': 'lingual',
    'MOrF': 'medialorbitofrontal', 'MT': 'middletemporal',
    'Op': 'parsopercularis', 'Or': 'parsorbitalis', 'Tr': 'parstriangularis',
    'PaC': 'paracentral', 'PaH': 'parahippocampal', 'PerCa': 'pericalcarine',
    'PoC': 'postcentral', 'PoCg': 'posteriorcingulate', 'PreC': 'precentral',
    'PreCu': 'precuneus', 'RoACg': 'rostralanteriorcingulate',
    'RoMF': 'rostralmiddlefrontal', 'SF': 'superiorfrontal',
    'SP': 'superiorparietal', 'ST': 'superiortemporal', 'SM': 'supramarginal',
    'TrT': 'transversetemporal',
}


def _section(title):
    print('\n' + '=' * 78)
    print(title)
    print('=' * 78)


def load_fmri_eids(h5_file):
    """
    Load the clean 7-digit UKB eids from `fMRI_aparc_eID` (a float64 array
    aligned 1:1 with `fMRI_aparc_TS`). The sibling `fMRI_aparc_ID` field
    instead stores 14-digit `eid*1e7 + session_suffix` composites and would
    not match the sMRI CSV.
    """
    if 'fMRI_aparc_eID' not in h5_file:
        raise KeyError(
            "fMRI .mat is missing 'fMRI_aparc_eID' (the clean eid array)"
        )
    return h5_file['fMRI_aparc_eID'][:].flatten().astype(np.int64)


def load_smri_ids_in_order(smri_csv_path):
    """Load sMRI participant eids preserving CSV row order."""
    if not os.path.exists(smri_csv_path):
        raise FileNotFoundError(f'sMRI CSV not found: {smri_csv_path}')

    ids = []
    with open(smri_csv_path, mode='r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        if 'eid' not in reader.fieldnames:
            raise KeyError("sMRI CSV does not contain 'eid' column")
        for row in reader:
            eid = (row.get('eid') or '').strip()
            if eid:
                ids.append(int(eid))
    return ids


def load_smri_roi_order(smri_csv_path):
    """
    Read SA_<H>_<abbrev>_2_0 columns from the sMRI CSV header in their
    original column order and return a list of (hemi, region_name) pairs.

    Mirrors the 66-region ROI list produced by Code/sMRI_proc.py
    (SA columns excluding 'Total' aggregates).
    """
    timepoint = '_2_0'
    with open(smri_csv_path, mode='r', encoding='utf-8') as f:
        header = next(csv.reader(f))

    roi_order = []
    for col in header:
        if not col.startswith('SA_') or not col.endswith(timepoint):
            continue
        if 'Total' in col:
            continue
        body = col[len('SA_'):-len(timepoint)]
        hemi, _, abbrev = body.partition('_')
        if hemi not in ('L', 'R'):
            continue
        if abbrev not in _UKB_ABBREV_TO_REGION:
            raise ValueError(
                f'Unknown sMRI abbreviation in column {col!r}; update '
                '_UKB_ABBREV_TO_REGION'
            )
        roi_order.append((hemi, _UKB_ABBREV_TO_REGION[abbrev]))
    return roi_order


def build_fmri_to_smri_perm(smri_roi_order):
    """
    Build a 66-element list of indices into the 68-node fMRI atlas such that
    `fc_68[np.ix_(perm, perm)]` produces a 66x66 FC matrix in the sMRI
    ROI ordering. Returns (perm, dropped) where `dropped` is the two fMRI
    indices that fall out (expected: the temporalpole nodes).
    """
    perm = []
    for pair in smri_roi_order:
        if pair not in _FMRI_INDEX:
            raise ValueError(f'sMRI ROI {pair} not present in fMRI atlas')
        perm.append(_FMRI_INDEX[pair])
    if len(set(perm)) != len(perm):
        raise ValueError('Permutation contains duplicates')
    dropped = sorted(set(range(68)) - set(perm))
    return perm, dropped


def write_roi_alignment_report(report_path, smri_roi_order, perm):
    """Write a side-by-side CSV cross-check of the sMRI/fMRI ROI alignment."""
    os.makedirs(os.path.dirname(report_path), exist_ok=True)
    with open(report_path, mode='w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        writer.writerow([
            'smri_idx', 'hemisphere', 'roi_name',
            'fmri_idx_68', 'fmri_label_68',
        ])
        for smri_idx, ((hemi, region), fmri_idx) in enumerate(
            zip(smri_roi_order, perm)
        ):
            fmri_hemi, fmri_region = FMRI_68_LABELS[fmri_idx]
            writer.writerow([
                smri_idx, hemi, region,
                fmri_idx, f'{fmri_hemi}_{fmri_region}',
            ])
    print(f'  -> wrote {report_path}')


def compute_fc_for_subject(time_series, perm):
    """
    Compute the dense Pearson FC for one subject's BOLD time series, then
    permute/drop to the 66-node sMRI ordering. Returns a 66x66 numpy array
    with the diagonal zeroed (self-correlations are always 1.0 and meaningless
    as edge weights; zeroing here prevents arctanh(1)=inf in the training script).
    No per-subject sparsity threshold is applied — graph sparsification is
    handled by the group-level mask in train_fmri_stage1.py.
    """
    if time_series.shape[1] != 68:
        raise ValueError(
            f'Unexpected node count: {time_series.shape[1]} (expected 68)'
        )

    fc = np.corrcoef(time_series, rowvar=False)
    np.nan_to_num(fc, copy=False)

    fc = fc[np.ix_(perm, perm)]
    np.fill_diagonal(fc, 0.0)
    return fc


def run(fmri_path, save_path, smri_csv_path, roi_report_path):
    _section('UK Biobank fMRI -> 66-node FC pipeline (sMRI-aligned)')
    print(f'fMRI input : {fmri_path}')
    print(f'sMRI CSV   : {smri_csv_path}')
    print(f'FC output  : {save_path}')
    print(f'ROI report : {roi_report_path}')
    print('Dense FC   : diagonal zeroed; no per-subject threshold')

    # ------------------------------------------------------------------
    _section('[Step 1/5] Load sMRI ROI ordering (66 nodes)')
    smri_roi_order = load_smri_roi_order(smri_csv_path)
    if len(smri_roi_order) != 66:
        raise ValueError(
            f'Expected 66 sMRI ROIs, found {len(smri_roi_order)}'
        )
    print(f'  Loaded {len(smri_roi_order)} ROIs from {smri_csv_path}')
    print(f'  First 5 : {[f"{h}_{r}" for h, r in smri_roi_order[:5]]}')
    print(f'  Last 5  : {[f"{h}_{r}" for h, r in smri_roi_order[-5:]]}')

    # ------------------------------------------------------------------
    _section('[Step 2/5] Build fMRI(68) -> sMRI(66) name-based permutation')
    perm, dropped = build_fmri_to_smri_perm(smri_roi_order)
    print(f'  Matched {len(perm)} / 66 sMRI ROIs in fMRI atlas')
    print('  Dropped fMRI indices (0-based):')
    for idx in dropped:
        h, r = FMRI_68_LABELS[idx]
        print(f'    [{idx:>2}] {h}_{r}')
    print('  Sanity check (first 3 / last 3 alignment):')
    for smri_idx in [0, 1, 2, 63, 64, 65]:
        h, r = smri_roi_order[smri_idx]
        fh, fr = FMRI_68_LABELS[perm[smri_idx]]
        print(f'    sMRI[{smri_idx:>2}] {h}_{r:<28s} '
              f'<- fMRI[{perm[smri_idx]:>2}] {fh}_{fr}')
    write_roi_alignment_report(roi_report_path, smri_roi_order, perm)

    # ------------------------------------------------------------------
    _section('[Step 3/5] Stream subjects, compute FC, permute, threshold')
    fmri_by_id = {}
    n_skipped = 0

    with h5py.File(fmri_path, 'r') as f:
        ts_refs = f['fMRI_aparc_TS'][:]
        eids = load_fmri_eids(f)
        n_subjects = ts_refs.shape[1]
        if eids.shape[0] != n_subjects:
            raise ValueError(
                f'fMRI_aparc_eID length {eids.shape[0]} does not match '
                f'fMRI_aparc_TS length {n_subjects}'
            )
        print(f'  Found {n_subjects} subjects in {fmri_path}')

        for i in range(n_subjects):
            eid = int(eids[i])
            try:
                if eid in fmri_by_id:
                    continue  # repeat session for same eid; keep first only
                raw = f[ts_refs[0, i]][:]
                ts = raw.T if raw.shape[0] == 68 else raw
                fc66 = compute_fc_for_subject(ts, perm)
                fmri_by_id[eid] = fc66
            except Exception as e:
                n_skipped += 1
                if n_skipped <= 10:
                    print(f'  [WARN] skip idx={i} (eid={eid}): {e}')

            if (i + 1) % 1000 == 0:
                print(f'  ... processed {i + 1} / {n_subjects}')

    print(f'  Decoded {len(fmri_by_id)} unique fMRI subjects '
          f'(skipped {n_skipped})')

    # ------------------------------------------------------------------
    _section('[Step 4/5] Filter & reorder to sMRI eid set')
    smri_ids = load_smri_ids_in_order(smri_csv_path)
    aligned_ids = []
    aligned_matrices = []
    for eid in smri_ids:
        mat = fmri_by_id.get(eid)
        if mat is not None:
            aligned_ids.append(eid)
            aligned_matrices.append(mat)
    n_unmatched = len(smri_ids) - len(aligned_ids)
    print(f'  sMRI participants     : {len(smri_ids)}')
    print(f'  Unique fMRI eids      : {len(fmri_by_id)}')
    print(f'  Subjects in BOTH      : {len(aligned_ids)}')
    print(f'  In sMRI but no fMRI   : {n_unmatched}')

    if not aligned_matrices:
        raise RuntimeError('No subjects matched between sMRI and fMRI.')

    final_matrices = np.stack(aligned_matrices, axis=0).astype(np.float32)
    final_ids = np.asarray(aligned_ids, dtype=np.int64)
    print(f'  Final FC tensor shape : {final_matrices.shape}')
    print(f'  First 5 eids          : {final_ids[:5].tolist()}')

    # ------------------------------------------------------------------
    _section('[Step 5/5] Save aligned FC matrices and metadata')
    os.makedirs(os.path.dirname(save_path), exist_ok=True)

    roi_labels = np.array(
        [f'{h}_{r}' for h, r in smri_roi_order], dtype=object
    )
    mat_data = {
        'FC_Matrices': final_matrices,
        'Patient_IDs': final_ids,
        'ROI_Labels': roi_labels,
        'ROI_Hemispheres': np.array(
            [h for h, _ in smri_roi_order], dtype=object
        ),
        'ROI_Regions': np.array(
            [r for _, r in smri_roi_order], dtype=object
        ),
        'fMRI_To_sMRI_Perm': np.asarray(perm, dtype=np.int64),
        'Dropped_From_fMRI68': np.asarray(dropped, dtype=np.int64),
        'Aligned_To_sMRI': np.int64(1),
    }
    sio.savemat(save_path, mat_data, do_compression=True)
    print(f'  -> wrote {save_path}')
    print('\nDone. The .mat file is now ready to be paired with sMRI '
          'features (same 66 ROI order, same eid order) for GCN training.')


if __name__ == '__main__':
    run(FMRI_PATH, SAVE_FILE, SMRI_CSV_PATH, ROI_REPORT_FILE)
